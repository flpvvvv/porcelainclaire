-- Anonymous reading signals and honeypot hits.
-- Written only by server routes with the service role; RLS is enabled with no
-- policies, and anon/authenticated access is revoked.

create table if not exists public.reading_events (
  id          bigint generated by default as identity primary key,
  slug        text not null,
  visible_ms  integer not null check (visible_ms between 0 and 3600000),
  scroll_pct  smallint not null check (scroll_pct between 0 and 100),
  user_agent  text,
  referer     text,
  country     text,
  ip_hash     text not null,
  read_date   date not null default (now() at time zone 'utc')::date,
  created_at  timestamptz not null default now()
);

create unique index if not exists reading_events_daily_unique
  on public.reading_events (slug, ip_hash, read_date);

create index if not exists reading_events_created_at_idx
  on public.reading_events (created_at desc);

alter table public.reading_events enable row level security;
revoke all on table public.reading_events from anon, authenticated;
grant all on table public.reading_events to service_role;
grant usage, select on sequence public.reading_events_id_seq to service_role;

create table if not exists public.bot_trap_hits (
  id          bigint generated by default as identity primary key,
  path        text not null,
  user_agent  text,
  referer     text,
  country     text,
  ip_hash     text not null,
  hit_date    date not null default (now() at time zone 'utc')::date,
  created_at  timestamptz not null default now()
);

create unique index if not exists bot_trap_hits_daily_unique
  on public.bot_trap_hits (ip_hash, path, hit_date);

create index if not exists bot_trap_hits_created_at_idx
  on public.bot_trap_hits (created_at desc);

alter table public.bot_trap_hits enable row level security;
revoke all on table public.bot_trap_hits from anon, authenticated;
grant all on table public.bot_trap_hits to service_role;
grant usage, select on sequence public.bot_trap_hits_id_seq to service_role;
